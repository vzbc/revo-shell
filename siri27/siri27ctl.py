#!/usr/bin/env python3
"""Helper for System Settings › Apple Intelligence & Siri.

  siri27ctl.py hotkey apply            write ~/.config/hypr/configs/siri.lua from the config
                                       and re-bind it live (prints JSON {ok|error})
  siri27ctl.py models                  installed Ollama models (JSON)
  siri27ctl.py status                  Ollama server status (JSON)
  siri27ctl.py pull <name>             ollama pull, progress -> ~/.cache/siri27/pull.log
  siri27ctl.py import <name> <gguf>    add a local .gguf file as an Ollama model
  siri27ctl.py rm <name>               remove an Ollama model
  siri27ctl.py voices                  installed Piper voices (JSON)
  siri27ctl.py say <voice> <text>      preview a voice
  siri27ctl.py delete-history          delete Siri & Dictation history
"""
import json, os, re, subprocess, sys, tempfile, urllib.request

HOME = os.path.expanduser('~')
BASE = os.path.join(HOME, '.local/share/siri27')
CONF = os.path.join(HOME, '.config/siri27/config.json')
HYPR_LUA = os.path.join(HOME, '.config/hypr/configs/siri.lua')
STATE = os.path.join(BASE, 'hotkey.state')
CACHE = os.path.join(HOME, '.cache/siri27')
QS = 'qs ipc -p ' + HOME + '/.config/quickshell/macos call siri'
MODS = {'SUPER': 64, 'ALT': 8, 'CTRL': 4, 'CONTROL': 4, 'SHIFT': 1}


def conf():
    sys.path.insert(0, BASE)
    import siri27d  # noqa: E402  (shares defaults + merge)
    return siri27d.load_conf()


def out(**kw):
    print(json.dumps(kw, ensure_ascii=False))


def ollama_url(c=None):
    return (c or conf())['ollama']['url'].rstrip('/')


def norm_combo(s):
    parts = [p.strip() for p in s.replace('+', ' + ').split('+') if p.strip()]
    mods = [p.upper() for p in parts[:-1]]
    key = parts[-1] if parts else ''
    return mods, key


def combo_str(mods, key):
    return ' + '.join(mods + [key])


def lua(combo, locked):
    opts_p = '{ locked = true }' if locked else None
    opts_r = '{ release = true, locked = true }' if locked else '{ release = true }'
    lines = [
        'hl.bind(%s, hl.dsp.exec_cmd(%s)%s)' % (json.dumps(combo), json.dumps(QS + ' keyDown'), (', ' + opts_p) if opts_p else ''),
        'hl.bind(%s, hl.dsp.exec_cmd(%s), %s)' % (json.dumps(combo), json.dumps(QS + ' keyUp'), opts_r),
    ]
    return lines


def hotkey_apply():
    c = conf()
    combo = (c.get('shortcut') or '').strip()
    locked = bool(c.get('allow_when_locked'))
    old = open(STATE).read().strip() if os.path.exists(STATE) else ''
    binds = []
    if combo and combo.lower() != 'off':
        mods, key = norm_combo(combo)
        if not key:
            return out(error='Invalid shortcut.')
        combo = combo_str(mods, key)
        # conflict check against everything bound except our own previous combo
        mask = sum(MODS.get(m, 0) for m in mods)
        try:
            cur = json.loads(subprocess.run(['hyprctl', 'binds', '-j'], capture_output=True, text=True).stdout)
        except Exception:
            cur = []
        oldm, oldk = norm_combo(old) if old else ([], '')
        oldmask = sum(MODS.get(m, 0) for m in oldm)
        for b in cur:
            if b.get('modmask') == mask and b.get('key', '').lower() == key.lower():
                if old and oldmask == mask and oldk.lower() == key.lower():
                    continue
                return out(error='This keyboard shortcut is already in use by the system or another application. '
                                 'Please choose another shortcut or use Keyboard Preferences to customize other system shortcuts.',
                           title='Keyboard Shortcut in Use')
        binds = lua(combo, locked)
    text = ('-- Siri keyboard shortcut. Generated by System Settings › Apple Intelligence & Siri;\n'
            '-- press = Type to Siri, hold = speak to Siri (release to send).\n' + '\n'.join(binds) + '\n')
    with open(HYPR_LUA, 'w') as f:
        f.write(text)
    # live: drop the previous binding, add the new one
    code = ''
    if old and old.lower() != 'off':
        code += 'hl.unbind(%s);' % json.dumps(old)
    code += ';'.join(binds)
    if code:
        r = subprocess.run(['hyprctl', 'eval', code], capture_output=True, text=True)
        if r.stdout.strip() not in ('ok', ''):
            return out(error='Hyprland: ' + r.stdout.strip())
    with open(STATE, 'w') as f:
        f.write(combo if binds else 'off')
    out(ok=True, shortcut=combo if binds else 'off')


def api(path, body=None, method=None, timeout=4):
    req = urllib.request.Request(ollama_url() + path, data=json.dumps(body).encode() if body is not None else None,
                                 headers={'Content-Type': 'application/json'}, method=method)
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read() or b'{}')


def models():
    try:
        tags = api('/api/tags')
    except Exception as e:
        return out(running=False, models=[], error=str(e))
    ms = [{'name': m['name'], 'size': m.get('size', 0),
           'params': m.get('details', {}).get('parameter_size', ''),
           'quant': m.get('details', {}).get('quantization_level', ''),
           'family': m.get('details', {}).get('family', '')} for m in tags.get('models', [])]
    out(running=True, models=ms)


def status():
    try:
        v = api('/api/version')
        out(running=True, version=v.get('version', ''))
    except Exception as e:
        out(running=False, error=str(e))


def pull(name):
    os.makedirs(CACHE, exist_ok=True)
    log = os.path.join(CACHE, 'pull.log')
    with open(log, 'w') as f:
        f.write('starting %s\n' % name)
    try:
        req = urllib.request.Request(ollama_url() + '/api/pull', data=json.dumps({'model': name, 'stream': True}).encode(),
                                     headers={'Content-Type': 'application/json'})
        with urllib.request.urlopen(req, timeout=3600) as r:
            for line in r:
                d = json.loads(line or b'{}')
                if d.get('error'):
                    raise RuntimeError(d['error'])
                st = d.get('status', '')
                if d.get('total'):
                    st += ' %d%%' % (100 * d.get('completed', 0) // d['total'])
                with open(log, 'a') as f:
                    f.write(st + '\n')
        with open(log, 'a') as f:
            f.write('DONE\n')
    except Exception as e:
        with open(log, 'a') as f:
            f.write('ERROR %s\n' % e)


def import_gguf(name, path):
    path = os.path.abspath(os.path.expanduser(path))
    if not os.path.isfile(path):
        return out(error='File not found: ' + path)
    mf = tempfile.NamedTemporaryFile('w', suffix='.Modelfile', delete=False)
    mf.write('FROM %s\n' % path)
    mf.close()
    r = subprocess.run(['ollama', 'create', name, '-f', mf.name], capture_output=True, text=True)
    os.unlink(mf.name)
    if r.returncode:
        return out(error=(r.stderr or r.stdout).strip()[-400:])
    out(ok=True, name=name)


def rm(name):
    r = subprocess.run(['ollama', 'rm', name], capture_output=True, text=True)
    out(ok=r.returncode == 0, error=(r.stderr or '').strip())


def voices():
    d = os.path.join(BASE, 'voices')
    vs = []
    for f in sorted(os.listdir(d)) if os.path.isdir(d) else []:
        if not f.endswith('.onnx'):
            continue
        name = f[:-5]
        m = re.match(r'([a-z]{2})_([A-Z]{2})-([^-]+)-(\w+)$', name)
        info = {}
        try:
            info = json.load(open(os.path.join(d, f + '.json')))
        except Exception:
            pass
        lang = m.group(1) if m else name[:2]
        vs.append({'id': name, 'lang': lang, 'region': m.group(2) if m else '',
                   'name': ' '.join(w.upper() if len(w) <= 3 and w not in ('low',) else w.title()
                                    for w in (m.group(3) if m else name).split('_')),
                   'quality': m.group(4) if m else '',
                   'language': info.get('language', {}).get('name_english', lang)})
    out(voices=vs)


def say(voice, text):
    sys.path.insert(0, BASE)
    import siri27d
    c = siri27d.load_conf()
    model = os.path.join(BASE, 'voices', voice + '.onnx')
    wav = tempfile.mktemp(suffix='.wav', prefix='siri27-preview-')
    subprocess.run([siri27d.PIPER, '--model', model, '--output_file', wav], input=text, text=True,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if os.path.exists(wav):
        subprocess.run(['pw-play', wav], stderr=subprocess.DEVNULL)
        os.unlink(wav)


VOICE_URL = 'https://huggingface.co/rhasspy/piper-voices/resolve/main/%s/%s_%s/%s/%s/%s'


def voice_get(vid):
    """Download a Piper voice (e.g. en_US-amy-medium); progress -> ~/.cache/siri27/voice.log"""
    m = re.match(r'([a-z]{2})_([A-Z]{2})-([^-]+)-(\w+)$', vid)
    os.makedirs(CACHE, exist_ok=True)
    log = os.path.join(CACHE, 'voice.log')
    if not m:
        open(log, 'w').write('ERROR bad voice id\n'); return
    d = os.path.join(BASE, 'voices')
    try:
        for ext in ('.onnx.json', '.onnx'):
            url = VOICE_URL % (m.group(1), m.group(1), m.group(2), m.group(3), m.group(4), vid + ext)
            dst = os.path.join(d, vid + ext)
            with urllib.request.urlopen(url, timeout=60) as r, open(dst + '.part', 'wb') as f:
                total = int(r.headers.get('Content-Length') or 0); got = 0
                while True:
                    b = r.read(1 << 16)
                    if not b:
                        break
                    f.write(b); got += len(b)
                    if total:
                        open(log, 'w').write('downloading %d%%\n' % (100 * got // total))
            os.replace(dst + '.part', dst)
        open(log, 'w').write('DONE\n')
    except Exception as e:
        open(log, 'w').write('ERROR %s\n' % e)


def delete_history():
    n = 0
    for p in (os.path.join(BASE, 'history.jsonl'),):
        if os.path.exists(p):
            os.unlink(p); n += 1
    for f in os.listdir(tempfile.gettempdir()):
        if f.startswith('siri27-'):
            try:
                os.unlink(os.path.join(tempfile.gettempdir(), f)); n += 1
            except OSError:
                pass
    out(ok=True, removed=n)


if __name__ == '__main__':
    a = sys.argv[1:]
    cmd = a[0] if a else ''
    if cmd == 'hotkey' and a[1:2] == ['apply']: hotkey_apply()
    elif cmd == 'models': models()
    elif cmd == 'status': status()
    elif cmd == 'pull': pull(a[1])
    elif cmd == 'import': import_gguf(a[1], a[2])
    elif cmd == 'rm': rm(a[1])
    elif cmd == 'voices': voices()
    elif cmd == 'say': say(a[1], ' '.join(a[2:]))
    elif cmd == 'voice-get': voice_get(a[1])
    elif cmd == 'delete-history': delete_history()
    else: print(__doc__)
